import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/examples/jsm/loaders/DRACOLoader.js';
import { RGBELoader } from 'three/examples/jsm/loaders/RGBELoader.js';
import { buildStudio } from './studio.js';
const q = new URLSearchParams(location.search);
const variants = JSON.parse(q.get('v'));
const W = +(q.get('w')||360), H = +(q.get('h')||640);
const r = new THREE.WebGLRenderer({ antialias: true, alpha: true, preserveDrawingBuffer: true });
r.setSize(W * variants.length, H); r.autoClear = false;
document.body.style.cssText = 'margin:0;background:' + (q.get('bg') || '#131c2b'); document.body.appendChild(r.domElement);
const scene = new THREE.Scene();
const d = new DRACOLoader().setDecoderPath('assets/draco/');
const hdr = await new RGBELoader().loadAsync('assets/env/studio-2k.hdr'); hdr.mapping = THREE.EquirectangularReflectionMapping;
const g = await new GLTFLoader().setDRACOLoader(d).loadAsync(q.get('m') || 'assets/model/ewer-2k.glb');
scene.add(g.scene);
let mat; g.scene.traverse(o => { if (o.isMesh) mat = o.material; });
const cam = new THREE.PerspectiveCamera(30, W / H, 0.1, 50);
r.setScissorTest(true);
const cache = {};
variants.forEach((v, i) => {
  r.toneMapping = THREE[(v.tm || 'AgX') + 'ToneMapping']; r.toneMappingExposure = v.ex ?? 1;
  const key = JSON.stringify(v.studio || null);
  scene.environment = v.studio ? (cache[key] ||= buildStudio(r, hdr, v.studio)) : hdr;
  scene.environmentRotation.set(0, v.rot || 0, 0); scene.environmentIntensity = v.ei ?? 1;
  mat.aoMapIntensity = v.ao ?? 1; mat.needsUpdate = true;
  const a = v.az || 0, dist = v.d || 6.4;
  cam.position.set(Math.sin(a) * dist, v.y ?? 0.3, Math.cos(a) * dist); cam.lookAt(0, v.ty || 0, 0);
  r.setViewport(i * W, 0, W, H); r.setScissor(i * W, 0, W, H); r.render(scene, cam);
});
window.done = true;
